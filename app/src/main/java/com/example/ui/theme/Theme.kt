val VeriCryptShapes = Shapes(
    extraSmall = RoundedCornerShape(6.dp),
    small = RoundedCornerShape(10.dp),
    medium = RoundedCornerShape(14.dp),
    large = RoundedCornerShape(18.dp),
    extraLarge = RoundedCornerShape(24.dp)
)

@Composable
fun VeriCryptTheme(
    themeMode: com.example.data.ThemeMode = com.example.data.ThemeMode.SYSTEM,
    darkTheme: Boolean = isSystemInDarkTheme(),
    content: @Composable () -> Unit
) {
    val isSystemDark = isSystemInDarkTheme()
    val colorScheme = when (themeMode) {
        com.example.data.ThemeMode.SYSTEM -> if (isSystemDark || darkTheme) DarkColorScheme else LightColorScheme
        com.example.data.ThemeMode.DARK -> DarkColorScheme
        com.example.data.ThemeMode.OLED -> OledColorScheme
        com.example.data.ThemeMode.LIGHT -> LightColorScheme
    }

    MaterialTheme(
        colorScheme = colorScheme,
        typography = Typography,
        shapes = VeriCryptShapes,
        content = content
    )
}
